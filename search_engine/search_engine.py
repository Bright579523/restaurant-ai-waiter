if __name__ == "__main__":
    engine = MenuSearchEngine()

    tests = [
        ("Mango Lassi", None),
        ("spinach paneer", {"is_vegetarian": True}),
        ("chicken", {"max_price": 16.0, "exclude_allergens": ["f"]}),
    ]

    for query, filters in tests:
        label = f"Query='{query}'"
        if filters:
            label += f"  filters={filters}"
        print(f"\n--- {label} ---")

        for r in engine.search(query, filters=filters, top_k=3):
            # Print with ASCII compatibility to avoid encode errors
            name_ascii = r['name'].encode('ascii', errors='replace').decode('ascii')
            cat_ascii = r['category'].encode('ascii', errors='replace').decode('ascii')
            print(
                f"  [{r['similarity_score']:.3f}] #{r['item_id']} "
                f"{name_ascii} - {r['price']:.2f} EUR  "
                f"({cat_ascii})"
            )
