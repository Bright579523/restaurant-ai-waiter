"""
search_engine.py — Hybrid Menu Search Engine
==============================================
Provides MenuSearchEngine, the core retrieval component of the ReDi Restaurant
AI Waiter system.  It combines:

1. **Metadata filtering** — SQL-like Boolean filters on dietary flags,
   meal type, price ceiling, ingredient presence, and allergen codes.
2. **Semantic ranking** — Cosine-similarity scoring between the user's
   query embedding and the pre-computed menu embeddings.

The engine loads everything from a pickle cache generated by
build_embeddings.py, so startup is fast (no re-encoding on every run).

Usage:
    from search_engine import MenuSearchEngine
    engine = MenuSearchEngine()
    results = engine.search("spicy lamb curry", filters={"max_price": 18}, top_k=5)
"""

import os
import pickle

import numpy as np
import pandas as pd
from sentence_transformers import SentenceTransformer
from sklearn.metrics.pairwise import cosine_similarity


class MenuSearchEngine:
    """Hybrid metadata-filter + vector-similarity search over the ReDi Restaurant menu."""

    def __init__(self, cache_path: str = "embeddings/menu_embeddings.pkl"):
        if not os.path.exists(cache_path):
            raise FileNotFoundError(
                f"{cache_path} not found — run  python build_embeddings.py  first."
            )

        print(f"Loading search engine from {cache_path}...")
        with open(cache_path, "rb") as f:
            cache = pickle.load(f)

        self.df: pd.DataFrame = cache["dataframe"]
        self.embeddings: np.ndarray = cache["embeddings"]
        self.model_name: str = cache.get(
            "model_name", "paraphrase-multilingual-MiniLM-L12-v2"
        )

        self.model = SentenceTransformer(self.model_name)
        print("Search engine ready")

    # ── Public API ───────────────────────────────────────────
    def search(
        self,
        query: str,
        filters: dict | None = None,
        top_k: int = 5,
    ) -> list[dict]:
        """
        Return up to *top_k* menu items matching *query* and *filters*.

        Supported filter keys
        ---------------------
        is_vegetarian       : bool
        is_vegan_possible   : bool
        is_lunch_menu       : bool
        meal_type           : str   ('main', 'starter', 'side', 'dessert', 'drink')
        max_price           : float
        contains_ingredients: list[str]  e.g. ['chicken', 'paneer']
        exclude_ingredients : list[str]  e.g. ['lamb']
        exclude_allergens   : list[str]  e.g. ['f', 'g']

        Returns
        -------
        list[dict]  — each dict has item_id, name, description_de, price,
                      category, meal_type, dietary flags, allergen_codes,
                      and similarity_score.
        """
        mask = self._apply_filters(filters)

        matched_idx = np.where(mask)[0]
        if len(matched_idx) == 0:
            return []

        # Semantic ranking via cosine similarity
        query_vec = self.model.encode([query])
        similarities = cosine_similarity(query_vec, self.embeddings[matched_idx])[0]

        k = min(top_k, len(matched_idx))
        top_local = np.argsort(similarities)[::-1][:k]

        return [
            self._row_to_dict(matched_idx[i], similarities[i]) for i in top_local
        ]

    # ── Private helpers ──────────────────────────────────────
    def _apply_filters(self, filters: dict | None) -> np.ndarray:
        """Build a boolean mask over self.df from the given filter dict."""
        mask = np.ones(len(self.df), dtype=bool)
        if not filters:
            return mask

        # Boolean flag filters
        for key in ("is_vegetarian", "is_vegan_possible", "is_lunch_menu"):
            if key in filters:
                mask &= self.df[key] == filters[key]

        # Categorical filter
        if filters.get("meal_type"):
            mask &= self.df["meal_type"] == filters["meal_type"]

        # Price ceiling
        if filters.get("max_price") is not None:
            mask &= self.df["price"] <= float(filters["max_price"])

        # Allergen exclusion  (allergen_codes is a comma-separated string)
        for code in filters.get("exclude_allergens", []):
            mask &= ~(
                self.df["allergen_codes"]
                .fillna("")
                .str.lower()
                .str.contains(code.strip().lower())
            )

        # Ingredient inclusion / exclusion via binary columns
        for ing in filters.get("contains_ingredients", []):
            col = f"contains_{ing.strip().lower()}"
            if col in self.df.columns:
                mask &= self.df[col] == True  # noqa: E712

        for ing in filters.get("exclude_ingredients", []):
            col = f"contains_{ing.strip().lower()}"
            if col in self.df.columns:
                mask &= self.df[col] == False  # noqa: E712

        return mask

    def _row_to_dict(self, idx: int, score: float) -> dict:
        """Convert a DataFrame row + similarity score into a result dict."""
        row = self.df.iloc[idx]
        return {
            "item_id": int(row["item_id"]),
            "name": str(row["name"]),
            "description_de": str(row["description_de"]) if pd.notna(row["description_de"]) else "",
            "price": float(row["price"]),
            "category": str(row["category"]),
            "meal_type": str(row["meal_type"]),
            "is_lunch_menu": bool(row["is_lunch_menu"]),
            "is_vegetarian": bool(row["is_vegetarian"]),
            "is_vegan_possible": bool(row["is_vegan_possible"]),
            "allergen_codes": str(row["allergen_codes"]) if pd.notna(row["allergen_codes"]) else "",
            "similarity_score": score,
        }


